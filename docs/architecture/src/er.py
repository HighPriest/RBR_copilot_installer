"""ER diagrams: the server's catalogue/auth side, and the installer's local state.

Run from the repository root:
    python docs/architecture/src/er.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from diagramkit import Ink, Kit  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def server(path):
    c = Kit(2320, 1180)
    c.title(40, 24, "ER-1 — Server: authentication, catalogue and protocol documents",
            "Every box is a table, a file or a wire document. PK/FK marks the key columns; "
            "a dashed box is derived, a dashed line a logical reference (no database constraint).")

    # ------------------------------------------------------------------ auth
    c.zone(40, 120, 600, 390, "SERVER — AUTH DATABASE", "libSQL, ./data/auth.db (--db-url)", Ink.auth)
    c.er_entity(70, 175, 540, "TOKENS", [
        ("PK", "token_hash", "TEXT"),
        ("", "label", "TEXT NULL"),
        ("", "created_at", "INTEGER"),
        ("", "expires_at", "INTEGER NULL"),
        ("", "revoked", "INTEGER 0|1"),
    ], subtitle="sha256(raw key); the raw key is never stored", accent=Ink.auth)

    c.er_entity(70, 370, 540, "GRANTS", [
        ("PK,FK", "token_hash", "TEXT"),
        ("PK", "directory", "TEXT"),
    ], subtitle="one row per directory a credential may list/download", accent=Ink.auth)

    # ------------------------------------------------------------- catalogue
    c.zone(680, 120, 1600, 960, "SERVER — DATA ROOT", "./data (--data): one folder per game", Ink.server)
    c.er_entity(710, 175, 520, "GAME", [
        ("PK", "id", "TEXT [a-z0-9_-]+"),
    ], subtitle="data/<game>/ — 'motd' and 'reports' are reserved", accent=Ink.server)

    c.er_entity(710, 303, 520, "ACCESS_DIRECTORY", [
        ("PK,FK", "game", "TEXT"),
        ("PK", "name", "TEXT [a-z0-9_-]+"),
    ], subtitle="packages/<directory>/ — the AUTH unit, not the UI category", accent=Ink.server)

    c.er_entity(710, 431, 520, "PACKAGE", [
        ("PK,FK", "game", "TEXT"),
        ("PK,FK", "directory", "TEXT"),
        ("PK", "name", "TEXT  path, no .."),
        ("", "version", "TEXT"),
        ("", "size", "INTEGER"),
        ("", "sha256", "TEXT hex"),
        ("", "updated_at", "UNIX s"),
        ("", "display_name", "TEXT NULL"),
        ("", "exclusive_group", "TEXT NULL"),
    ], subtitle="packages/<dir>/<name>.zip — name IS the UI tree", accent=Ink.server)

    c.er_entity(710, 706, 520, "SIDECAR", [
        ("PK,FK", "directory / name", "TEXT"),
        ("", "version", "TEXT NULL"),
        ("", "display_name", "TEXT NULL"),
        ("", "description", "TEXT NULL"),
        ("", "exclusive_group", "TEXT NULL"),
        ("", "requires", "[dir/name]"),
    ], subtitle="<name>.toml next to the zip: the ONLY metadata source", accent=Ink.server)

    c.er_entity(710, 918, 520, "PACKAGE_REQUIRES", [
        ("PK,FK", "from", "game/dir/name"),
        ("PK", "to", "directory/name"),
        ("", "resolves in", "the same game"),
    ], subtitle="flattened requires[]; cross-directory rules checked at publish", accent=Ink.server)

    c.er_entity(1330, 175, 460, "SCHEMA", [
        ("PK,FK", "game", "TEXT"),
        ("", "sha256", "TEXT raw bytes"),
        ("", "bytes", "TOML"),
    ], subtitle="<game>/schema.toml — installers compare the hash", accent=Ink.server)

    c.er_entity(1330, 324, 460, "SCHEMA_CATEGORY", [
        ("PK,FK", "game", "TEXT"),
        ("PK", "id", "TEXT"),
        ("", "select", "one | any"),
        ("", "install_root", "game (a token)"),
    ], subtitle="what the catalogue may contain, and which asks one pick", accent=Ink.server)

    c.er_entity(1330, 476, 460, "MOTD", [
        ("PK", "lang", "TEXT [a-z]{2,8}"),
    ], subtitle="motd/<lang>.txt, 'en' fallback, no auth", accent=Ink.server)

    c.er_entity(1330, 760, 460, "CONFLICT_RECORD", [
        ("PK", "day + line", "JSONL line"),
        ("", "received_at", "INTEGER server clock"),
        ("FK", "game", "TEXT"),
        ("", "installer", "TEXT version"),
        ("", "conflicts[]", "file + packages[]"),
    ], subtitle="reports/conflicts-YYYY-MM-DD.jsonl, append-only", accent=Ink.server)

    c.er_entity(1840, 175, 410, "MANIFEST", [
        ("PK", "packages[]", "PackageInfo"),
        ("", "schemas{}", "game → GameSchema"),
    ], subtitle="data/manifest.json, GENERATED by manifest gen", accent=Ink.protocol, derived=True)

    # -------------------------------------------------------------- protocol
    c.zone(40, 540, 600, 380, "PROTOCOL DOCUMENTS", "shared/ — serde types, no I/O", Ink.protocol)
    c.er_entity(70, 605, 540, "KeyStatus", [
        ("", "expires_at", "INTEGER NULL"),
    ], subtitle="200 body of GET /whoami; 401 says nothing else", accent=Ink.protocol)

    c.er_entity(70, 722, 540, "ConflictReport", [
        ("", "game", "TEXT"),
        ("", "installer", "TEXT"),
        ("", "conflicts[]", "file + packages[]"),
    ], subtitle="POST /report/conflict, 8 KiB cap, no identity", accent=Ink.protocol)

    # -------------------------------------------------------------- relations
    c.relation("TOKENS", "bottom", "GRANTS", "top", 0.35, 0.35, label="issues", card_a="1",
               card_b="0..*", color=Ink.auth, label_offset=(22, 0))
    c.relation("GRANTS", "right", "ACCESS_DIRECTORY", "left", 0.5, 0.5,
               label="logical FK", color=Ink.auth, dashed=True,
               route=[(610, 412), (660, 412), (660, 354), (710, 354)], label_at=0.28,
               label_offset=(0, 13))
    c.relation("GAME", "bottom", "ACCESS_DIRECTORY", "top", 0.45, 0.45, label="contains",
               card_a="1", card_b="0..*", color=Ink.server, label_offset=(17, 0))
    c.relation("ACCESS_DIRECTORY", "bottom", "PACKAGE", "top", 0.45, 0.45,
               label="packages/", card_a="1", card_b="0..*", color=Ink.server, label_offset=(17, 0))
    c.relation("PACKAGE", "bottom", "SIDECAR", "top", 0.5, 0.5, label="describes", card_a="1",
               card_b="0..1", color=Ink.server, label_offset=(20, 0))
    c.relation("SIDECAR", "bottom", "PACKAGE_REQUIRES", "top", 0.5, 0.5, label="requires[]",
               card_a="1", card_b="0..*", color=Ink.server, label_offset=(26, 0))
    c.relation("GAME", "right", "SCHEMA", "left", 0.5, 0.5, label="", card_a="1",
               card_b="1", color=Ink.server, label_offset=(0, -15))
    c.relation("SCHEMA", "bottom", "SCHEMA_CATEGORY", "top", 0.3, 0.3, label="declares",
               card_a="1", card_b="1..*", color=Ink.server, label_offset=(24, 0))
    c.relation("MANIFEST", "left", "PACKAGE", "right", 0.5, 0.88,
               label="generated from", color=Ink.protocol, dashed=True,
               route=[(1840, 236), (1800, 236), (1800, 660), (1230, 660)], label_at=0.55)

    # ---------------------------------------------------------- reading guide
    guide = (
        "READING THE MODEL\n"
        "• A package is identified by game + directory + name — never by name alone.\n"
        "• 'name' is a path: category / tree level… / leaf. It is a LOOKUP KEY, never\n"
        "   joined onto a filesystem path.\n"
        "• SIDECAR is optional and 1:1 with PACKAGE; delete a key and it disappears at\n"
        "   the next 'manifest gen' (the manifest is a pure function of zips + sidecars).\n"
        "• GRANTS.directory has no database constraint: the name is resolved against\n"
        "   the catalogue, which is why a grant can name a directory of any game.\n"
        "• CONFLICT_RECORD is diagnostics: nothing in the catalogue is derived from it\n"
        "   except 'manifest gen' warnings."
    )
    c.note(1840, 330, 410, guide, font_size=12)

    c.legend(40, 1110, [(Ink.auth, "authentication"), (Ink.server, "server files"),
                        (Ink.protocol, "protocol / derived")], columns=3)
    c.text(40, 1140, "Sources: server/migrations/0001_init.sql · shared/src/lib.rs · server/src/store.rs",
           c.mono(11), Ink.faint)
    return c.save(os.path.join(path, "er-server.png"))


def installer(path):
    c = Kit(2060, 1460)
    c.title(40, 24, "ER-2 — Installer: what a run leaves in the game folder ( .pacenotes )",
            "The same package identity (game/directory/name) and the same sha256 travel from ER-1 into "
            "the cache, and from the cache into the ledger.")

    # ----------------------------------------------------------------- cache
    c.zone(40, 120, 880, 600, "DOWNLOAD CACHE", ".pacenotes\\cache\\ — per game folder", Ink.client)
    c.er_entity(70, 185, 820, "CACHE_INDEX", [
        ("PK", "version", "INTEGER"),
        ("", "packages{}", "key → CacheEntry"),
    ], subtitle="cache.json; Missing / Unreadable / Loaded are distinct states", accent=Ink.client)

    c.er_entity(70, 313, 820, "CACHE_ENTRY", [
        ("PK", "key", "game/directory/name"),
        ("FK", "sha256", "→ payload file"),
        ("", "version", "TEXT"),
        ("", "size", "INTEGER"),
        ("", "updated_at", "INTEGER"),
        ("", "display_name", "TEXT NULL"),
        ("", "exclusive_group", "TEXT NULL"),
        ("", "requires", "[dir/name]"),
    ], subtitle="a snapshot of PackageInfo, so the tree works offline", accent=Ink.client)

    c.er_entity(70, 567, 820, "CACHE_PAYLOAD", [
        ("PK", "sha256", "TEXT"),
        ("", "file", "<sha256>.zip"),
    ], subtitle="content-addressed: dedupe, integrity, rollback", accent=Ink.client)

    # ---------------------------------------------------------------- ledger
    c.zone(40, 760, 880, 640, "INSTALL LEDGER", ".pacenotes\\installed.json — written atomically", Ink.client)
    c.er_entity(70, 825, 820, "LEDGER", [
        ("PK", "version", "INTEGER"),
        ("", "packages{}", "key → LedgerEntry"),
    ], subtitle="Missing / Unreadable / Loaded; an unreadable ledger is never overwritten", accent=Ink.client)

    c.er_entity(70, 953, 820, "LEDGER_ENTRY", [
        ("PK", "key", "game/directory/name"),
        ("", "sha256", "what was installed"),
        ("", "version", "TEXT"),
        ("", "exclusive_group", "TEXT NULL"),
        ("", "state", "installed | installing"),
    ], subtitle="'installing' is written BEFORE extraction (write-ahead)", accent=Ink.client)

    c.er_entity(70, 1165, 820, "LEDGER_FILE", [
        ("PK,FK", "entry", "ledger key"),
        ("PK", "path_folded", "case-folded"),
        ("", "path", "as written, /-separated"),
        ("", "sha256", "what WE wrote"),
        ("", "prior", "absent | identical | backup"),
    ], subtitle="ownership per file: changed files are left alone on uninstall", accent=Ink.client)

    # --------------------------------------------------------- restore points
    c.zone(960, 120, 960, 640, "RESTORE POINTS", ".pacenotes\\restore\\<UTC stamp>\\ — the way back", Ink.disk)
    c.er_entity(990, 185, 900, "RESTORE_POINT", [
        ("PK", "name", "2026-10-27T12-11-31Z"),
        ("", "ledger.json", "the ledger BEFORE the run"),
        ("", "files/", "originals it replaced"),
    ], subtitle="one per run that changed the folder, plus one per restore", accent=Ink.disk)

    c.er_entity(990, 336, 900, "SAVED_FILE", [
        ("PK,FK", "point", "TEXT"),
        ("PK", "path", "relative, /-separated"),
        ("", "bytes", "original content"),
    ], subtitle="copied only when the bytes differ from what replaces them", accent=Ink.disk)

    c.er_entity(990, 466, 900, "LEDGER_SNAPSHOT", [
        ("PK,FK", "point", "TEXT"),
        ("", "packages{}", "frozen LedgerEntry map"),
    ], subtitle="what makes restore remove what came later, not just copy back", accent=Ink.disk, derived=True)

    # -------------------------------------------------------------- run logs
    c.zone(960, 800, 960, 340, "RUN LOGS", ".pacenotes\\logs\\install-<stamp>.log", Ink.disk)
    c.er_entity(990, 865, 900, "RUN_LOG", [
        ("PK", "stamp", "UTC date-time"),
        ("", "lines", "what the run said"),
    ], subtitle="one per run; the newest five are kept", accent=Ink.disk)
    c.note(990, 975, 900,
           "The log is the only artefact a user can send back. It is attached when scene 3 settles a "
           "folder, and it replays what was said before that — a crash before the folder is known goes "
           "beside the .exe instead.", font_size=12)

    # -------------------------------------------------------------- relations
    c.relation("CACHE_INDEX", "bottom", "CACHE_ENTRY", "top", 0.5, 0.5, label="packages{}",
               card_a="1", card_b="0..*", color=Ink.client)
    c.relation("CACHE_ENTRY", "bottom", "CACHE_PAYLOAD", "top", 0.5, 0.5, label="sha256",
               card_a="0..*", card_b="1", color=Ink.client)
    c.relation("LEDGER", "bottom", "LEDGER_ENTRY", "top", 0.5, 0.5, label="packages{}",
               card_a="1", card_b="0..*", color=Ink.client)
    c.relation("LEDGER_ENTRY", "bottom", "LEDGER_FILE", "top", 0.5, 0.5, label="files{}",
               card_a="1", card_b="1..*", color=Ink.client)
    c.relation("RESTORE_POINT", "bottom", "SAVED_FILE", "top", 0.35, 0.35, label="files/",
               card_a="1", card_b="0..*", color=Ink.disk)
    c.relation("RESTORE_POINT", "right", "LEDGER_SNAPSHOT", "right", 0.55, 0.6,
               label="snapshot", color=Ink.disk, dashed=True,
               route=[(1890, 253), (1904, 253), (1904, 516), (1890, 516)], label_at=0.5)
    c.relation("CACHE_ENTRY", "right", "LEDGER_ENTRY", "right", 0.55, 0.45,
               label="installed as (same key, same sha256)", color=Ink.link, dashed=True,
               route=[(890, 445), (920, 445), (920, 1030), (890, 1030)], label_at=0.5)
    c.note(990, 590, 900,
           "LEDGER_FILE.prior = backup(<point>) names one of these points: the original bytes are "
           "under files/ and are copied back on uninstall. prior = identical means nothing was "
           "copied because the bytes already matched, so the original is rebuilt from the cached "
           "payload — and if that payload is gone, the file is left alone, never deleted.",
           font_size=12)

    c.legend(40, 1420, [(Ink.client, "cache / ledger"), (Ink.disk, "restore points / logs"),
                        (Ink.link, "cross-links")], columns=3)
    return c.save(os.path.join(path, "er-installer.png"))


if __name__ == "__main__":
    target = OUT
    print(server(target))
    print(installer(target))

/// One `[[category]]`: id, select, install_root.
type Category = (String, String, String);

/// A `[[category]]` still being read.
type OpenCategory = (Option<String>, Option<String>, Option<String>);

/// Compiles `schemas/<game>.toml` into a static table, so the installer takes
/// its categories from its own copy, never the server's, and nothing parses
/// TOML at runtime.
pub fn generate_schema_table() {
    let dir = std::path::Path::new("../schemas");
    println!("cargo:rerun-if-changed=../schemas");

    let mut files: Vec<std::path::PathBuf> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "toml")
        })
        .collect();
    files.sort();

    let mut out = String::from(
        "// GENERATED by build.rs from schemas/*.toml. Do not edit.\n\
         pub static SCHEMAS: &[Schema] = &[\n",
    );
    for path in &files {
        out.push_str(&schema_entry(path));
    }
    out.push_str("];\n");

    let target =
        std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("schema_table.rs");
    std::fs::write(&target, out).unwrap_or_else(|e| panic!("writing the schema table: {e}"));
}

fn schema_entry(path: &std::path::Path) -> String {
    let game = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or_else(|| panic!("odd schema filename {}", path.display()))
        .to_string();
    println!("cargo:rerun-if-changed={}", path.display());

    let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("reading {game}: {e}"));
    let text = String::from_utf8(bytes).unwrap_or_else(|_| panic!("{game} is not UTF-8"));
    let categories = read_schema(&game, &text);
    assert!(!categories.is_empty(), "{game} declares no [[category]]");

    let absolute = std::fs::canonicalize(path)
        .unwrap_or_else(|e| panic!("resolving {game}: {e}"))
        .display()
        .to_string()
        .replace(r"\\?\", "");
    let mut entry = format!(
        "    Schema {{\n        game: {game:?},\n        toml: include_bytes!({absolute:?}),\n        categories: &[\n"
    );
    for (id, select, install_root) in &categories {
        entry.push_str(&format!(
            "            Category {{ id: {id:?}, select: {select:?}, install_root: {install_root:?} }},\n"
        ));
    }
    entry.push_str("        ],\n    },\n");
    entry
}

/// Reads `[[category]]` blocks of `id`, `select` and `install_root` and panics
/// on anything else, so a schema beyond that format fails the build with a
/// line number instead of disagreeing with the server's reading of the file.
fn read_schema(game: &str, text: &str) -> Vec<Category> {
    let mut categories = Vec::new();
    let mut open: Option<OpenCategory> = None;
    for (index, raw) in text.lines().enumerate() {
        let line_number = index + 1;
        let line = raw.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        if line == "[[category]]" {
            if let Some(finished) = open.replace((None, None, None)) {
                categories.push(complete(game, finished, line_number));
            }
            continue;
        }
        let (key, value) = key_value(game, line, line_number);
        let current = open
            .as_mut()
            .unwrap_or_else(|| panic!("{game} line {line_number}: {key:?} outside a [[category]]"));
        match key {
            "id" => current.0 = Some(value.to_string()),
            "select" => current.1 = Some(value.to_string()),
            "install_root" => current.2 = Some(value.to_string()),
            other => panic!("{game} line {line_number}: unknown key {other:?}"),
        }
    }
    if let Some(finished) = open {
        categories.push(complete(game, finished, text.lines().count()));
    }
    categories
}

/// `key = "value"`, refusing escapes, which the format does not need.
fn key_value<'a>(game: &str, line: &'a str, line_number: usize) -> (&'a str, &'a str) {
    let (key, value) = line
        .split_once('=')
        .unwrap_or_else(|| panic!("{game} line {line_number}: not `key = value`: {line:?}"));
    let value = value
        .trim()
        .strip_prefix('"')
        .and_then(|value| value.strip_suffix('"'))
        .unwrap_or_else(|| panic!("{game} line {line_number}: value must be a quoted string"));
    assert!(
        !value.contains('\\') && !value.contains('"'),
        "{game} line {line_number}: escapes are not supported in a schema"
    );
    (key.trim(), value)
}

fn complete(game: &str, (id, select, install_root): OpenCategory, before_line: usize) -> Category {
    let id =
        id.unwrap_or_else(|| panic!("{game}: a [[category]] before line {before_line} has no id"));
    let select = select.unwrap_or_else(|| panic!("{game}: category {id:?} has no select"));
    let install_root =
        install_root.unwrap_or_else(|| panic!("{game}: category {id:?} has no install_root"));
    (id, select, install_root)
}
